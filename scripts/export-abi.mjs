// Run from: ROOT. Exports the ABI produced by `forge build` to typed TS (as const) + JSON.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
const contracts = ['ElysiaLedger']
mkdirSync('packages/contracts-abi/abi', { recursive: true })
let index = '// GENERATED by scripts/export-abi.mjs from contracts/out. Do not edit by hand.\n'
for (const name of contracts) {
  const art = JSON.parse(readFileSync(`contracts/out/${name}.sol/${name}.json`, 'utf8'))
  writeFileSync(`packages/contracts-abi/abi/${name}.json`, JSON.stringify(art.abi, null, 2) + '\n')
  const camel = name[0].toLowerCase() + name.slice(1)
  index += `export const ${camel}Abi = ${JSON.stringify(art.abi, null, 2)} as const\n`
}
writeFileSync('packages/contracts-abi/src/index.ts', index)
